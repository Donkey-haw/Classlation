import type { Topic, TopicCategory } from "../domain/game";

type TopicSeed = readonly [word: string, emoji: string, hint: string];

function createCategory(
  id: string,
  name: string,
  emoji: string,
  description: string,
  seeds: readonly TopicSeed[],
): TopicCategory {
  return {
    id,
    name,
    emoji,
    description,
    topics: seeds.map(([word, topicEmoji, hint], index) => ({
      id: `${id}-${index + 1}-${word}`,
      word,
      emoji: topicEmoji,
      hint,
      category: name,
      source: "recommended",
    })),
  };
}

